#!/usr/bin/env python3
"""Bake the bundled DejaVu Sans font into a compact SDL texture atlas."""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT_PATH = ROOT / "assets/fonts/DejaVuSans.ttf"
ATLAS_PATH = ROOT / "assets/font_atlas.png"
HEADER_PATH = ROOT / "src/generated_font.hpp"
FONT_SIZE = 22
CELL_W = CELL_H = 32
ATLAS_COLS = 32
CODEPOINTS = list(range(32, 0x250)) + [
    0x2010, 0x2011, 0x2012, 0x2013, 0x2014, 0x2018, 0x2019,
    0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2122,
]

font = ImageFont.truetype(str(FONT_PATH), FONT_SIZE)
rows = math.ceil(len(CODEPOINTS) / ATLAS_COLS)
atlas = Image.new("RGBA", (ATLAS_COLS * CELL_W, rows * CELL_H), (255, 255, 255, 0))
draw = ImageDraw.Draw(atlas)
glyphs = []

for i, codepoint in enumerate(CODEPOINTS):
    ch = chr(codepoint)
    col, row = i % ATLAS_COLS, i // ATLAS_COLS
    cell_x, cell_y = col * CELL_W, row * CELL_H
    left, top, right, bottom = font.getbbox(ch, anchor="ls")
    draw.text((cell_x + 2, cell_y + 24), ch, font=font, anchor="ls", fill=(255, 255, 255, 255))
    glyphs.append((
        codepoint,
        cell_x + 2 + left,
        cell_y + 24 + top,
        max(0, right - left),
        max(0, bottom - top),
        left,
        top,
        int(round(font.getlength(ch))),
    ))

atlas.save(ATLAS_PATH, optimize=True)
with HEADER_PATH.open("w", encoding="utf-8") as out:
    out.write("// Generated by tools/generate_font_atlas.py; do not edit by hand.\n")
    out.write("#pragma once\n#include <cstdint>\n\nnamespace fontdata {\n")
    out.write("constexpr int kBaseSize = %d;\n" % FONT_SIZE)
    out.write("struct Glyph { uint32_t codepoint; uint16_t x,y,w,h; int16_t bearingX,bearingY; uint16_t advance; };\n")
    out.write("constexpr Glyph kGlyphs[] = {\n")
    for glyph in glyphs:
        out.write("    {%s},\n" % ",".join(str(v) for v in glyph))
    out.write("};\nconstexpr unsigned kGlyphCount = sizeof(kGlyphs) / sizeof(kGlyphs[0]);\n}\n")
print("Wrote %s glyphs to %s" % (len(glyphs), ATLAS_PATH))
